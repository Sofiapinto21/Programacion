### Operadores Aritméticos ###

print(3 + 4) # Suma
print(3 - 4) # Resta
print(3 * 4) # Multiplicación
print(3 / 4) # División
print(10 % 3) # Módulo
print(10 // 3) # División entera
print(2 ** 3) # Potencia
print(2 ** 3 + 3 -7 / 1 // 4) # Operaciones combinadas

print("Hola " + "Python " + "Qué tal?") # Concatenación de strings
print("Hola " + str(3)) # Concatenación de string con int (conversión a string)
print("Hola " * 3) # Repetición de strings
print("Hola " * (2 ** 3 + 3)) # Repetición de strings con operaciones combinadas

my_float = 3.5 * 2
print("Hola " * int(my_float))

#### Operadores de Comparación ###
print(3 > 4) # Mayor que
print(3 < 4) # Menor que
print(3 >= 4) # Mayor o igual que
print(3 <= 4) # Menor o igual que
print(3 == 4) # Igual que
print(3 != 4) # Diferente que
print(3 > 4 == 2) # Operaciones combinadas

print("Hola" > "Python") # Comparación de strings
print("Hola" < "Python") # Comparación de strings
print("Hola" >= "Zola") # Ordenamiento alfabético por el valor ASCII de los caracteres
print(len("Hola") >= len("Python")) # Cuenta de caracteres
print("Hola" <= "Python") # Comparación de strings
print("Hola" == "Python") # Comparación de strings
print("Hola" != "Python") # Comparación de strings

#### Operadores Lógicos ###
print(3 > 4 and 2 < 3) # AND
print(3 > 4 or 2 < 3) # OR
print(not (3 > 4)) # NOT
